#!/usr/bin/env node
/**
 * Import 400×400 JPG previews → trimmed transparent PNGs + badgeIconDataUrls.ts
 * Source: app/temp/Custom-Name-Badge-400x400-Vector-preview/.../*.jpg
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const SOURCE_DIR = path.join(
  root,
  "app/temp/Custom-Name-Badge-400x400-Vector-preview",
);
const OUT_DIR = path.join(root, "public/badge-icons");
const DATA_URLS_PATH = path.join(root, "app/constants/badgeIconDataUrls.ts");

/** Filename prefix → badge icon id */
const FILE_TO_ID = [
  ["Cross-", "cross"],
  ["Praying-Hands-", "praying-hands"],
  ["Stethoscope-", "stethoscope"],
  ["Real-Estate-", "house-key"],
  ["Coffee-", "coffee"],
  ["Store-Front-", "storefront"],
  ["Tooth-", "tooth"],
  ["Chefs-Hat-", "chef-hat"],
  ["Knife-Fork-", "utensils"],
  ["Graduation-Cap-", "graduation-cap"],
  ["Paw-", "paw"],
  ["Medical-Cross-", "medical-cross"],
  ["Baby-Feet-", "baby-feet"],
  ["Aeroplane-", "airplane"],
  ["Apple-", "apple"],
];

async function removeNearWhiteBackground(buffer) {
  const { data, info } = await sharp(buffer)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const { width, height, channels } = info;
  for (let i = 0; i < data.length; i += channels) {
    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];
    const max = Math.max(r, g, b);
    const min = Math.min(r, g, b);
    if (max > 248 && min > 242) {
      data[i + 3] = 0;
    } else if (max > 225 && min > 215) {
      const lum = (r + g + b) / 3;
      const a = Math.round(Math.max(0, Math.min(255, (238 - lum) * 10)));
      data[i + 3] = Math.min(data[i + 3] ?? 255, a);
    }
  }

  return sharp(data, { raw: { width, height, channels: 4 } })
    .trim({ threshold: 2 })
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toBuffer();
}

async function processIcon(inputPath, id) {
  const raw = await sharp(inputPath)
    .flatten({ background: "#ffffff" })
    .png()
    .toBuffer();
  let png = await removeNearWhiteBackground(raw);
  const meta = await sharp(png).metadata();
  const maxDim = Math.max(meta.width ?? 0, meta.height ?? 0);
  if (maxDim > 160) {
    png = await sharp(png)
      .resize({
        width: meta.width >= meta.height ? 160 : undefined,
        height: meta.height > meta.width ? 160 : undefined,
        fit: "inside",
        kernel: sharp.kernel.lanczos3,
      })
      .png({ compressionLevel: 9, adaptiveFiltering: true })
      .toBuffer();
  }
  const outPath = path.join(OUT_DIR, `${id}.png`);
  await sharp(png).toFile(outPath);
  return sharp(outPath).metadata();
}

function resolveSourceFile(prefix) {
  const files = fs.readdirSync(SOURCE_DIR);
  const hit = files.find(
    (f) => f.startsWith(prefix) && /\.jpe?g$/i.test(f),
  );
  if (!hit) throw new Error(`No source file for prefix ${prefix}`);
  return path.join(SOURCE_DIR, hit);
}

async function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error("Missing source folder:", SOURCE_DIR);
    process.exit(1);
  }
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const metaEntries = [];
  const dataEntries = [];

  for (const [prefix, id] of FILE_TO_ID) {
    const src = resolveSourceFile(prefix);
    const meta = await processIcon(src, id);
    const b64 = fs.readFileSync(path.join(OUT_DIR, `${id}.png`)).toString("base64");
    metaEntries.push(`  "${id}": { width: ${meta.width}, height: ${meta.height} }`);
    dataEntries.push(`  "${id}": "data:image/png;base64,${b64}"`);
    console.log(id, meta.width, "x", meta.height, meta.hasAlpha ? "RGBA" : "RGB");
  }

  const ts = `// Generated by scripts/import-badge-icons-from-preview.mjs — do not edit by hand.\n\nexport const BADGE_ICON_NATURAL_SIZE: Record<string, { width: number; height: number }> = {\n${metaEntries.join(",\n")}\n};\n\nexport const BADGE_ICON_DATA_URLS: Record<string, string> = {\n${dataEntries.join(",\n")}\n};\n`;
  fs.writeFileSync(DATA_URLS_PATH, ts);
  console.log("Wrote", DATA_URLS_PATH);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
