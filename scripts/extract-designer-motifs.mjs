/**
 * One-shot: diff themed Designer SVGs vs base (heart) per size, emit TS for designerMotifs.
 * Run: node scripts/extract-designer-motifs.mjs
 *
 * Requires themed source SVGs under public/templates/sign/ (Coffee Bean, Golf, …).
 * If those assets were removed after generating designerMotifs.generated.ts, restore them
 * from git before re-running.
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const require = createRequire(import.meta.url);
const { DOMParser, XMLSerializer } = require("xmldom");
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const signDir = join(root, "public/templates/sign");

function normalizePathD(d) {
  return (d || "").replace(/\s+/g, " ").trim();
}

function pathDataEqual(a, b) {
  return normalizePathD(a) === normalizePathD(b);
}

function firstMoveTo(d) {
  const m = normalizePathD(d).match(/M\s*([-0-9.eE]+)\s*[,\s]\s*([-0-9.eE]+)/i);
  if (!m) return null;
  return { x: Number(m[1]), y: Number(m[2]) };
}

function getOuterPathD(doc) {
  const paths = doc.getElementsByTagName("path");
  for (let i = 0; i < paths.length; i++) {
    const p = paths[i];
    const cls = (p.getAttribute("class") || "").toLowerCase();
    if (cls.includes("fil0") && p.getAttribute("d")) return p.getAttribute("d");
  }
  if (paths.length) return paths[0].getAttribute("d");
  return "";
}

function isMotifCandidate(pathEl, outerPathD) {
  const id = (pathEl.getAttribute("id") || "").trim();
  const d = pathEl.getAttribute("d");
  if (!d) return false;
  if (id === "Inner") return false;
  if (pathDataEqual(d, outerPathD)) return false;
  if (id === "Border") return false;
  const cls = (pathEl.getAttribute("class") || "").toLowerCase();
  const isNamedAccent =
    id === "Design" ||
    id.startsWith("Design_") ||
    id.includes("Design") ||
    id.includes("Top") ||
    id.includes("Bottom");
  const isOrphanFil2 = id === "" && cls.includes("fil2");
  return isNamedAccent || isOrphanFil2;
}

/** All motif paths (non-Border trim art) in file's native coordinates. */
function collectMotifPathElements(doc) {
  const outerPathD = getOuterPathD(doc);
  const paths = doc.getElementsByTagName("path");
  const out = [];
  for (let i = 0; i < paths.length; i++) {
    const p = paths[i];
    if (!isMotifCandidate(p, outerPathD)) continue;
    out.push(p);
  }
  return { outerPathD, elements: out };
}

function escapeD(d) {
  return d.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function serializeMotifGroup(doc, elements, translateX, translateY) {
  const ser = new XMLSerializer();
  const parts = [];
  for (const el of elements) {
    const clone = el.cloneNode(true);
    clone.removeAttribute("id");
    clone.removeAttribute("class");
    const s = ser.serializeToString(clone);
    parts.push(s);
  }
  const inner = parts.join("");
  if (translateX === 0 && translateY === 0) return inner;
  return `<g transform="translate(${translateX},${translateY})">${inner}</g>`;
}

const SIZES = [
  { key: "2x5", base: "Designer 2x5.svg" },
  { key: "2_8x7", base: "Designer 2.8x7.svg" },
  { key: "4x9", base: "Designer 4x9.svg" },
  { key: "4_25x11", base: "Designer 4.25 x 11.svg" },
];

const THEMES = [
  { id: "heart", file: null },
  { id: "coffee", file: "Designer Coffee Bean {size}.svg" },
  { id: "golf", file: "Designer Golf {size}.svg" },
  { id: "house", file: "Designer House {size}.svg" },
  { id: "money", file: "Designer Money {size}.svg" },
  { id: "paws", file: "Designer Paws {size}.svg" },
  { id: "recycle", file: "Designer Recycle {size}.svg" },
];

/** Per-size filename overrides (Corel export naming inconsistencies). */
const THEME_FILE_OVERRIDES = {
  "coffee-4_25x11": "Designer 4.25 x 11.svg",
  "recycle-2_8x7": "Designer recycle 2.8x7.svg",
  "recycle-4_25x11": "Designer Recylce 4.25 x 11.svg",
};

function sizeFileSuffix(key) {
  if (key === "2x5") return "2x5";
  if (key === "2_8x7") return "2.8x7";
  if (key === "4x9") return "4x9";
  if (key === "4_25x11") return "4.25 x 11";
  return key;
}

function loadSvg(rel) {
  const p = join(signDir, rel);
  const buf = readFileSync(p);
  if (buf.length >= 2 && buf[0] === 0xff && buf[1] === 0xfe) {
    return buf.slice(2).toString("utf16le");
  }
  return buf.toString("utf8");
}

function parse(xml) {
  return new DOMParser().parseFromString(xml, "image/svg+xml");
}

const lines = [];
lines.push(`// AUTO-GENERATED by scripts/extract-designer-motifs.mjs — do not edit by hand`);
lines.push(`export const DESIGNER_MOTIF_FRAGMENTS: Record<string, Record<string, string>> = {`);

for (const { key } of SIZES) {
  const suffix = sizeFileSuffix(key);
  const baseName = `Designer ${suffix}.svg`;
  const baseXml = loadSvg(baseName);
  const baseDoc = parse(baseXml);
  const baseOuter = getOuterPathD(baseDoc);
  const baseM = firstMoveTo(baseOuter);

  lines.push(`  "${key}": {`);

  for (const theme of THEMES) {
    let frag;
    if (theme.id === "heart") {
      const { elements } = collectMotifPathElements(baseDoc);
      frag = serializeMotifGroup(baseDoc, elements, 0, 0);
    } else {
      const overrideKey = `${theme.id}-${key}`;
      const fname =
        THEME_FILE_OVERRIDES[overrideKey] ?? theme.file.replace("{size}", suffix);
      let themedXml;
      try {
        themedXml = loadSvg(fname);
      } catch (e) {
        console.warn("Missing themed file:", fname);
        lines.push(`    "${theme.id}": "", // MISSING ${fname}`);
        continue;
      }
      const themedDoc = parse(themedXml);
      const themedOuter = getOuterPathD(themedDoc);
      const themedM = firstMoveTo(themedOuter);
      let tx = 0;
      let ty = 0;
      if (baseM && themedM) {
        tx = baseM.x - themedM.x;
        ty = baseM.y - themedM.y;
      }
      const { elements } = collectMotifPathElements(themedDoc);
      frag = serializeMotifGroup(themedDoc, elements, tx, ty);
    }
    const escaped = frag.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
    lines.push(`    "${theme.id}": \`${escaped}\`,`);
  }

  lines.push(`  },`);
}

lines.push(`};`);
lines.push("");

const outPath = join(root, "app/data/designerMotifs.generated.ts");
writeFileSync(outPath, lines.join("\n"), "utf8");
console.log("Wrote", outPath);
